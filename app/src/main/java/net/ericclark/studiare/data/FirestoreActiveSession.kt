    val scoreDirection: String = "ASC",
    // --------------------------------

    // Mode specific options
    val numberOfAnswers: Int = ModeOptionDefaults.NUMBER_OF_ANSWERS,
    val showCorrectLetters: Boolean = ModeOptionDefaults.SHOW_CORRECT_LETTERS,
    val limitAnswerPool: Boolean = true,
    val cardOrder: String = "Random",
    val mcOptions: Map<String, List<String>> = emptyMap(),
    val pickerOptions: List<String> = emptyList(),
    val matchingCardIdsOnScreen: List<String> = emptyList(),
    val matchedPairs: List<String> = emptyList(),
    val incorrectCardIds: List<String> = emptyList(),
    val isGraded: Boolean = false,
    val allowMultipleGuesses: Boolean = true,
    val enableStt: Boolean = false,
    val hideAnswerText: Boolean = false,
    val attemptedCardIds: List<String> = emptyList(),
    val fingersAndToes: Boolean = ModeOptionDefaults.FINGERS_AND_TOES,

    // Memory
    val maxMemoryTiles: Int = ModeOptionDefaults.MAX_MEMORY_TILES,
    val memorySelectedId1: String? = null,
    val memorySelectedSide1: String? = null,
    val memorySelectedId2: String? = null,
    val memorySelectedSide2: String? = null,

    // Crossword
    val crosswordWords: List<CrosswordWord> = emptyList(),
    val crosswordUserInputs: Map<String, String> = emptyMap(),
    val crosswordGridWidth: Int = 0,
    val crosswordGridHeight: Int = 0,
    val showCorrectWords: Boolean = ModeOptionDefaults.SHOW_CORRECT_WORDS
) {
    constructor() : this(id = UUID.randomUUID().toString())

    fun toAppActiveSession(): ActiveSession {
        return ActiveSession(
            id = this.id,
            deckId = this.deckId,
            // Same remaps as Room's MIGRATION_11_12/12_13: an older synced session can still say
            // "audio"+graded (pre audio-mode-split) or one of the original 4 split-out modes
            // (pre 4→2 consolidation) — see AppDatabase.kt for why each remap is lossless.
            mode = when {
                this.mode.lowercase() == "audio" && this.isGraded -> SessionMode.SPOKEN_LISTEN
                this.mode.uppercase() in setOf("SPEECH_TO_TEXT", "LISTEN_TYPE") -> SessionMode.TYPED_LISTEN
                this.mode.uppercase() in setOf("TEXT_TO_SPEECH", "LISTEN_SPEAK") -> SessionMode.SPOKEN_LISTEN
                else -> this.mode.toSessionMode()
            },
            isWeighted = this.isWeighted,
            difficulties = this.difficulties,
            totalCards = this.totalCards,
            shuffledCardIds = this.shuffledCardIds,
            quizPromptSide = this.quizPromptSide.toCardSide(),
            currentCardIndex = this.currentCardIndex,
            wrongSelections = this.wrongSelections,
            correctAnswerFound = this.correctAnswerFound,
            showQuestion = this.showQuestion,
            isFlipped = this.isFlipped,
            firstTryCorrectCount = this.firstTryCorrectCount,
            hasAttempted = this.hasAttempted,
            createdAt = this.createdAt,
            lastAccessed = this.lastAccessed,
            schedulingMode = this.schedulingMode.toSchedulingMode(),
            audioPlaybackSpeed = this.audioPlaybackSpeed.toFloat(),
            audioReplayCount = this.audioReplayCount,
            audioAutoAdvance = this.audioAutoAdvance,
            audioAnswerDelaySeconds = this.audioAnswerDelaySeconds,
            audioNextCardDelaySeconds = this.audioNextCardDelaySeconds,
            gridDensity = this.gridDensity,
            freeformShowBothSides = this.freeformShowBothSides,
            freeformSwipeNavigation = this.freeformSwipeNavigation,
            typingIgnoreFormatting = this.typingIgnoreFormatting,
            typingAutoSubmit = this.typingAutoSubmit,
            typingDisableAutocorrect = this.typingDisableAutocorrect,
            typingShowLengthHint = this.typingShowLengthHint,
            flashcardAutoFlipSeconds = this.flashcardAutoFlipSeconds,
            flashcardDoubleTapToFlip = this.flashcardDoubleTapToFlip,
            flashcardRandomizeFirstSide = this.flashcardRandomizeFirstSide,
            requireConfirmTap = this.requireConfirmTap,
            autoAdvanceAfterCorrect = this.autoAdvanceAfterCorrect,
            autoAdvanceDelaySeconds = this.autoAdvanceDelaySeconds,
            autoListen = this.autoListen,
            speakingFrontSpeed = this.speakingFrontSpeed.toFloat(),
            speakingBackSpeed = this.speakingBackSpeed.toFloat(),
            listResetPosition = this.listResetPosition,
            listDimWrongGuesses = this.listDimWrongGuesses,
            listRemoveGuessed = this.listRemoveGuessed,
            matchingHighlightStyle = this.matchingHighlightStyle,
            matchingWrongDelayMs = this.matchingWrongDelayMs,
            matchingShowCorrectDialog = this.matchingShowCorrectDialog,
            anagramFirstLetterHint = this.anagramFirstLetterHint,
            anagramUppercase = this.anagramUppercase,
            anagramColorVowels = this.anagramColorVowels,
            crosswordHighlightWord = this.crosswordHighlightWord,
            crosswordAutoAdvanceCell = this.crosswordAutoAdvanceCell,
            crosswordCompactClues = this.crosswordCompactClues,
            crosswordFeedbackMode = this.crosswordFeedbackMode,
            hangmanMaxMistakes = this.hangmanMaxMistakes,
            hangmanRevealSpeedMs = this.hangmanRevealSpeedMs,
            hangmanHideVisual = this.hangmanHideVisual,
            memoryFlipAnimation = this.memoryFlipAnimation,
            memoryGrayMatched = this.memoryGrayMatched,
            memoryPeekSeconds = this.memoryPeekSeconds,
            memoryWrongPairMs = this.memoryWrongPairMs,
            wordSearchHideFound = this.wordSearchHideFound,
            wordSearchHighlightColor = this.wordSearchHighlightColor,

            // --- NEW MAPPERS ---
            selectionMode = runCatching { SelectionMode.valueOf(this.selectionMode) }.getOrDefault(SelectionMode.ANY),
            selectedTags = this.selectedTags,
            excludeKnown = this.excludeKnown,
            sortDirection = runCatching { Direction.valueOf(this.sortDirection) }.getOrDefault(Direction.ASC),
            sortSide = this.sortSide.toCardSide(),
            alphabetStart = this.alphabetStart,
            alphabetEnd = this.alphabetEnd,
            filterSide = this.filterSide.toCardSide(),
            cardOrderStart = this.cardOrderStart,
            cardOrderEnd = this.cardOrderEnd,
            timeValue = this.timeValue,
            timeUnit = runCatching { TimeUnit.valueOf(this.timeUnit) }.getOrDefault(TimeUnit.DAYS),
            filterType = runCatching { FilterType.valueOf(this.filterType) }.getOrDefault(FilterType.EXCLUDE),
            reviewCountThreshold = this.reviewCountThreshold,
            reviewCountDirection = runCatching { Direction.valueOf(this.reviewCountDirection) }.getOrDefault(Direction.ASC),
            scoreThreshold = this.scoreThreshold,
            scoreDirection = runCatching { Direction.valueOf(this.scoreDirection) }.getOrDefault(Direction.ASC),
            // -------------------

            numberOfAnswers = this.numberOfAnswers,
            showCorrectLetters = this.showCorrectLetters,
            limitAnswerPool = this.limitAnswerPool,
            cardOrder = this.cardOrder.toSortMode(),
            mcOptions = this.mcOptions,
            pickerOptions = this.pickerOptions,
            matchingCardIdsOnScreen = this.matchingCardIdsOnScreen,
            matchedPairs = this.matchedPairs,
            incorrectCardIds = this.incorrectCardIds,
            isGraded = this.isGraded,
            allowMultipleGuesses = this.allowMultipleGuesses,
            enableStt = this.enableStt,
            hideAnswerText = this.hideAnswerText,
            attemptedCardIds = this.attemptedCardIds,
            fingersAndToes = this.fingersAndToes,
            maxMemoryTiles = this.maxMemoryTiles,
            memorySelectedId1 = this.memorySelectedId1,
            memorySelectedSide1 = this.memorySelectedSide1?.toCardSide(),
            memorySelectedId2 = this.memorySelectedId2,
            memorySelectedSide2 = this.memorySelectedSide2?.toCardSide(),
            crosswordWords = this.crosswordWords,
            crosswordUserInputs = this.crosswordUserInputs,
            crosswordGridWidth = this.crosswordGridWidth,
            crosswordGridHeight = this.crosswordGridHeight,
            showCorrectWords = this.showCorrectWords
        )
    }
}

